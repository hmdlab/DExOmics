#!/usr/bin/env python3
"""
31_paper_figures.py — リバイズ論文の残り図候補（fig6 分類 / fig7 解釈 / figS 群）
出力: results/figures/ + notes/figures/（PNG は Notion 掲載用）
"""
import os, json, numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

from dexo_paths import DATA_ROOT, PROJ_ROOT   # data/project roots: --data-root / DEXOMICS_DATA / ~/Data/DExOmics
ROOT = DATA_ROOT; R = f"{ROOT}/results"
OUT = f"{R}/figures"; NOTES = f"{PROJ_ROOT}/notes/figures"
os.makedirs(OUT, exist_ok=True); os.makedirs(NOTES, exist_ok=True)
plt.rcParams.update({"font.size": 8.5, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": "#e8e8e5", "grid.linewidth": 0.6, "axes.axisbelow": True,
                     "figure.facecolor": "white", "savefig.dpi": 300})
CB, CO, CA, CG = "#2a78d6", "#eb6834", "#1baf7a", "#7a7a76"

def save(fig, name):
    for ext in ["pdf", "png"]: fig.savefig(f"{OUT}/{name}.{ext}", bbox_inches="tight")
    fig.savefig(f"{NOTES}/{name}.png", bbox_inches="tight"); plt.close(fig); print("saved", name)

# ================= fig6: classification =================
a = pd.read_csv(f"{R}/exp4_dl/classification_from_scores.csv")   # (a) 回帰→閾値
b = pd.read_csv(f"{R}/exp4_dl/classification_direct.csv")        # (b) 直接分類
b = b[~b.model.str.contains("prior")]
amap = {"XGBoost(5seed)": "XGBoost", "CNN pretrained(3seed)": "CNN", "Ensemble": "Ensemble"}
bmap = {"xgb-clf": "XGBoost", "cnn-clf": "CNN", "ens-clf": "Ensemble"}
a["m"] = a.model.map(amap); b["m"] = b.model.map(bmap)
order = ["XGBoost", "CNN", "Ensemble"]
fig, axes = plt.subplots(1, 3, figsize=(7.6, 2.6))
# paired difference ens-clf (direct) − Ensemble (scores): regenerated by 29b when available, else the 2026-09-21 values
_pd = f"{R}/exp4_dl/classification_paired_diff.json"
_ann = {"macro_f1": "ens Δ = +0.031 [0.017, 0.043]", "prauc_down": "ens Δ = +0.077 [0.060, 0.096]"}
if os.path.exists(_pd):
    _d = json.load(open(_pd)); _d = _d[[k for k in _d if k != "bootstrap"][0]]
    _ann = {k: f"ens Δ = {v[1]:+.3f} [{v[0]:.3f}, {v[2]:.3f}]" for k, v in _d.items()}
for ax, metric, title, ann in [
        (axes[0], "macro_f1", "a  Macro-F1 (3-class)", _ann["macro_f1"]),
        (axes[1], "prauc_down", "b  PR-AUC (DOWN)", _ann["prauc_down"]),
        (axes[2], "recall_down", "c  DOWN recall", None)]:
    x = np.arange(3); w = 0.36
    va = [float(a[a.m == m][metric].iloc[0]) for m in order]
    vb = [float(b[b.m == m][metric].iloc[0]) for m in order]
    ax.bar(x - w / 2, va, w, color="#e2e1dd", edgecolor="#8a8985", label="regression → thresholds")
    ax.bar(x + w / 2, vb, w, color=CB, edgecolor="white", label="direct classification")
    for xi, (v1, v2) in enumerate(zip(va, vb)):
        ax.text(xi - w / 2, v1 + 0.008, f"{v1:.2f}", ha="center", fontsize=6.8)
        ax.text(xi + w / 2, v2 + 0.008, f"{v2:.2f}", ha="center", fontsize=6.8)
    ax.set_xticks(x); ax.set_xticklabels(order, fontsize=7.6)
    ax.set_title(title, loc="left", fontsize=9); ax.grid(axis="x", visible=False)
    ax.set_ylim(0, max(vb + va) * 1.3)
    if ann: ax.text(0.03, 0.95, ann, transform=ax.transAxes, fontsize=6.8, va="top", color="#52514e")
axes[2].text(0.03, 0.95, "precision 0.116 → 0.160 (ens)", transform=axes[2].transAxes, fontsize=6.8, va="top", color="#52514e")
axes[0].legend(frameon=False, fontsize=6.6, loc="lower right")
save(fig, "fig6_classification")

# ================= fig7: interpretability =================
SX = np.load(f"{R}/exp5_interp/shap_xgb_oof.npy"); xcols = json.load(open(f"{R}/exp5_interp/shap_xgb_cols.json"))
EGP = np.load(f"{R}/exp5_interp/eg_prom_oof.npy"); EGR = np.load(f"{R}/exp5_interp/eg_rna_oof.npy")
EGO = np.load(f"{R}/exp5_interp/eg_omics_oof.npy")
meta = json.load(open(f"{R}/exp5_interp/eg_meta.json")); ocols = meta["omics_cols"]
summ = json.load(open(f"{R}/exp5_interp/interp_summary.json"))
bind = pd.read_parquet(f"{R}/features/binding_gene_level.parquet")
prom_names = [c for c in bind.columns if c.startswith("prom__")]
rna_names = [c for c in bind.columns if c.startswith("rna__")]
cnn_fac = np.concatenate([EGP.sum(2), EGR.sum(2), EGO], axis=1)
cnn_names = prom_names + rna_names + ocols
xmap = {c: i for i, c in enumerate(xcols)}
shared = [c for c in cnn_names if c in xmap and c != "log_n_bins"]
mx = np.abs(SX[:, [xmap[c] for c in shared]]).mean(0); mx = mx / mx.sum()
mc = np.abs(cnn_fac[:, [cnn_names.index(c) for c in shared]]).mean(0); mc = mc / mc.sum()
combo = np.argsort(-(mx + mc))[:12]
labels = [shared[i].replace("prom__", "TF: ").replace("rna__", "RBP: ").replace("cnv__", "CNV: ").replace("methy_all__", "Me: ").replace("mutall__", "Mut: ").replace("mut__", "Mut: ") for i in combo]
fig, axes = plt.subplots(1, 3, figsize=(8.2, 2.9), gridspec_kw={"width_ratios": [1.3, 1, 0.9], "wspace": 0.5})
ax = axes[0]
ys = np.arange(len(combo))[::-1]
for y0, i in zip(ys, combo):
    ax.plot([mx[i], mc[i]], [y0, y0], color="#d9d8d3", lw=1.1, zorder=1)
    ax.plot(mx[i], y0, "o", color=CB, ms=4.5, zorder=2)
    ax.plot(mc[i], y0, "o", color=CO, ms=4.5, zorder=2)
ax.set_yticks(ys); ax.set_yticklabels(labels, fontsize=6.8)
ax.set_xlabel("importance share (mean |attribution|)")
ax.legend(handles=[Line2D([], [], color=CB, marker="o", lw=0, label="XGBoost (TreeSHAP)"),
                   Line2D([], [], color=CO, marker="o", lw=0, label="CNN (Expected Grad.)")],
          frameon=False, fontsize=6.2, loc="lower right", bbox_to_anchor=(1.02, -0.02))
ax.set_title("a  Top factors (both models)", loc="left", fontsize=9); ax.grid(axis="y", visible=False)
ax = axes[1]
grp = ["UP", "NonDEG", "DOWN"]; x = np.arange(3); w = 0.36
g1 = [summ["amp_xgb_cnv__mean_cn"]["group_means"][g] for g in grp]
g2 = [summ["amp_xgb_cnv__Amp_rate"]["group_means"][g] for g in grp]
ax.bar(x - w / 2, g1, w, color=CB, edgecolor="white", label="mean CN")
ax.bar(x + w / 2, g2, w, color="#7aa9e0", edgecolor="white", label="Amp rate")
ax.axhline(0, color="#7a7a76", lw=0.8)
ax.set_xticks(x); ax.set_xticklabels(grp, fontsize=7.6); ax.set_ylabel("mean signed SHAP (XGBoost)")
ax.text(0.35, 0.78, "SHAP vs log2FC:\nρ = 0.17 [0.10, 0.23]", transform=ax.transAxes, fontsize=6.4, color="#52514e")
ax.legend(frameon=False, fontsize=6.4, loc="lower left")
ax.set_title("b  Amplification vs direction", loc="left", fontsize=9); ax.grid(axis="x", visible=False)
ax = axes[2]
pf = pd.read_csv(f"{R}/exp5_interp/crossmodel_agreement.csv")
for j, (col, lab) in enumerate([("spearman", "rank ρ"), ("top20_jaccard", "top-20\nJaccard"), ("sign_concord", "sign\nagreement")]):
    ax.plot(np.full(5, j) + (np.arange(5) - 2) * 0.05, pf[col], "o", color=CA, ms=4)
    ax.plot([j - 0.2, j + 0.2], [pf[col].mean()] * 2, color="#0b0b0b", lw=1.4)
ax.plot([2 - 0.25, 2 + 0.25], [0.5, 0.5], color="#b9b8b3", lw=0.9, ls=":")
ax.text(2, 0.455, "chance", ha="center", fontsize=5.6, color="#8a8985")
ax.set_xticks(range(3)); ax.set_xticklabels(["rank ρ", "top-20\nJaccard", "sign\nagreement"], fontsize=7)
ax.set_ylim(0, 1); ax.set_title("c  Cross-model agreement", loc="left", fontsize=9); ax.grid(axis="x", visible=False)
save(fig, "fig7_interpretability")

